-- NYC Taxi Data Cleaning Project
-- January 2026 Yellow Taxi Trip Records
-- Step 4: Post-Cleaning Validation

-- 1. Compare raw and cleaned row counts

SELECT
    (SELECT COUNT(*)
     FROM NYC_TAXI_DQ.RAW.YELLOW_TAXI_RAW) AS RAW_ROWS,

    (SELECT COUNT(*)
     FROM NYC_TAXI_DQ.RAW.YELLOW_TAXI_CLEANED) AS CLEANED_ROWS;

-- 2. Check the number of records removed during cleaning

SELECT
    (SELECT COUNT(*)
     FROM NYC_TAXI_DQ.RAW.YELLOW_TAXI_RAW)
    -
    (SELECT COUNT(*)
     FROM NYC_TAXI_DQ.RAW.YELLOW_TAXI_CLEANED)
    AS REMOVED_ROWS;

-- 3. Confirm that no extreme-distance records remain

SELECT
    COUNT(*) AS EXTREME_DISTANCE_REMAINING
FROM NYC_TAXI_DQ.RAW.YELLOW_TAXI_CLEANED
WHERE TRIP_DISTANCE > 1000;

-- 4. Confirm that no negative-duration trips remain

SELECT
    COUNT(*) AS NEGATIVE_DURATION_REMAINING
FROM NYC_TAXI_DQ.RAW.YELLOW_TAXI_CLEANED
WHERE TPEP_DROPOFF_DATETIME < TPEP_PICKUP_DATETIME;

-- 5. Check for exact duplicate rows after cleaning

SELECT
    COUNT(*) AS TOTAL_ROWS,
    COUNT(DISTINCT HASH(*)) AS UNIQUE_ROWS,
    COUNT(*) - COUNT(DISTINCT HASH(*)) AS DUPLICATE_ROWS
FROM NYC_TAXI_DQ.RAW.YELLOW_TAXI_CLEANED;


-- 6. Check systematic NULL values after cleaning

SELECT
    COUNT_IF(PASSENGER_COUNT IS NULL) AS NULL_PASSENGER_COUNT,
    COUNT_IF(RATECODEID IS NULL) AS NULL_RATECODEID,
    COUNT_IF(STORE_AND_FWD_FLAG IS NULL) AS NULL_STORE_AND_FWD,
    COUNT_IF(CONGESTION_SURCHARGE IS NULL) AS NULL_CONGESTION,
    COUNT_IF(AIRPORT_FEE IS NULL) AS NULL_AIRPORT_FEE,
    COUNT_IF(CBD_CONGESTION_FEE IS NULL) AS NULL_CBD_CONGESTION_FEE
FROM NYC_TAXI_DQ.RAW.YELLOW_TAXI_CLEANED;

-- 7. Check critical fields for NULL values

SELECT
    COUNT_IF(VENDORID IS NULL) AS NULL_VENDORID,
    COUNT_IF(TPEP_PICKUP_DATETIME IS NULL) AS NULL_PICKUP,
    COUNT_IF(TPEP_DROPOFF_DATETIME IS NULL) AS NULL_DROPOFF,
    COUNT_IF(TRIP_DISTANCE IS NULL) AS NULL_DISTANCE,
    COUNT_IF(PULOCATIONID IS NULL) AS NULL_PICKUP_LOCATION,
    COUNT_IF(DOLOCATIONID IS NULL) AS NULL_DROPOFF_LOCATION,
    COUNT_IF(PAYMENT_TYPE IS NULL) AS NULL_PAYMENT_TYPE,
    COUNT_IF(FARE_AMOUNT IS NULL) AS NULL_FARE,
    COUNT_IF(TOTAL_AMOUNT IS NULL) AS NULL_TOTAL
FROM NYC_TAXI_DQ.RAW.YELLOW_TAXI_CLEANED;

-- 8. Check payment, rate code and vendor values after cleaning

SELECT
    COUNT_IF(PAYMENT_TYPE NOT IN (0,1,2,3,4)) AS INVALID_PAYMENT_TYPE,

    COUNT_IF(
        RATECODEID IS NOT NULL
        AND RATECODEID NOT IN (1,2,3,4,5,6,99)
    ) AS INVALID_RATECODE,

    COUNT_IF(VENDORID NOT IN (1,2,6,7)) AS INVALID_VENDOR

FROM NYC_TAXI_DQ.RAW.YELLOW_TAXI_CLEANED;

-- 9. Check store and forward values after cleaning

SELECT
    COUNT_IF(
        STORE_AND_FWD_FLAG IS NOT NULL
        AND STORE_AND_FWD_FLAG NOT IN ('Y','N')
    ) AS INVALID_STORE_FLAG
FROM NYC_TAXI_DQ.RAW.YELLOW_TAXI_CLEANED;


-- 10. Check pickup and dropoff location IDs against the lookup table

SELECT
    COUNT_IF(p.LOCATIONID IS NULL) AS INVALID_PICKUP_IDS,
    COUNT_IF(d.LOCATIONID IS NULL) AS INVALID_DROPOFF_IDS
FROM NYC_TAXI_DQ.RAW.YELLOW_TAXI_CLEANED t
LEFT JOIN NYC_TAXI_DQ.LOOKUP.TAXI_ZONE_LOOKUP p
    ON t.PULOCATIONID = p.LOCATIONID
LEFT JOIN NYC_TAXI_DQ.LOOKUP.TAXI_ZONE_LOOKUP d
    ON t.DOLOCATIONID = d.LOCATIONID;


-- 11. Check that financial values remain within the observed data

SELECT
    COUNT_IF(FARE_AMOUNT < 0) AS NEGATIVE_FARE,
    COUNT_IF(TIP_AMOUNT < 0) AS NEGATIVE_TIP,
    COUNT_IF(TOLLS_AMOUNT < 0) AS NEGATIVE_TOLLS,
    COUNT_IF(TOTAL_AMOUNT < 0) AS NEGATIVE_TOTAL
FROM NYC_TAXI_DQ.RAW.YELLOW_TAXI_CLEANED;


-- 12. Check the table structure

SELECT
    COUNT(*) AS TOTAL_COLUMNS
FROM NYC_TAXI_DQ.INFORMATION_SCHEMA.COLUMNS
WHERE TABLE_SCHEMA = 'RAW'
  AND TABLE_NAME = 'YELLOW_TAXI_CLEANED';

-- 13. Check the timestamp columns

SELECT
    COLUMN_NAME,
    DATA_TYPE
FROM NYC_TAXI_DQ.INFORMATION_SCHEMA.COLUMNS
WHERE TABLE_SCHEMA = 'RAW'
  AND TABLE_NAME = 'YELLOW_TAXI_CLEANED'
  AND COLUMN_NAME IN (
      'TPEP_PICKUP_DATETIME',
      'TPEP_DROPOFF_DATETIME'
  )
ORDER BY COLUMN_NAME;

-- 14. Confirm that the raw table is still available
--     and was kept separate from the cleaned table.

SELECT
    COUNT(*) AS RAW_ROWS_AFTER_CLEANING
FROM NYC_TAXI_DQ.RAW.YELLOW_TAXI_RAW;