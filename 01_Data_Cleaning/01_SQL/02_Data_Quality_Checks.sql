-- NYC Taxi Data Cleaning Project
-- January 2026 Yellow Taxi Trip Records
-- Step 2: Data Quality Checks

USE DATABASE NYC_TAXI_DQ;
USE SCHEMA RAW;

-- 1. Check for possible duplicate records

-- Check records that have the same main trip details.
SELECT
    VENDORID,
    TPEP_PICKUP_DATETIME,
    TPEP_DROPOFF_DATETIME,
    PULOCATIONID,
    DOLOCATIONID,
    TRIP_DISTANCE,
    COUNT(*) AS RECORD_COUNT
FROM YELLOW_TAXI_RAW
GROUP BY
    VENDORID,
    TPEP_PICKUP_DATETIME,
    TPEP_DROPOFF_DATETIME,
    PULOCATIONID,
    DOLOCATIONID,
    TRIP_DISTANCE
HAVING COUNT(*) > 1
ORDER BY RECORD_COUNT DESC;

-- Check for exact duplicate rows using a row fingerprint.
SELECT
    COUNT(*) AS TOTAL_ROWS,
    COUNT(DISTINCT HASH(*)) AS UNIQUE_ROWS,
    COUNT(*) - COUNT(DISTINCT HASH(*)) AS DUPLICATE_ROWS
FROM YELLOW_TAXI_RAW;

-- 2. Check payment type values

SELECT
    PAYMENT_TYPE,
    COUNT(*) AS RECORD_COUNT
FROM YELLOW_TAXI_RAW
GROUP BY PAYMENT_TYPE
ORDER BY PAYMENT_TYPE;

-- 3. Check rate code values

SELECT
    RATECODEID,
    COUNT(*) AS RECORD_COUNT
FROM YELLOW_TAXI_RAW
GROUP BY RATECODEID
ORDER BY RATECODEID;

-- 4. Check vendor IDs

SELECT
    VENDORID,
    COUNT(*) AS RECORD_COUNT
FROM YELLOW_TAXI_RAW
GROUP BY VENDORID
ORDER BY VENDORID;

-- 5. Check store and forward values

SELECT
    STORE_AND_FWD_FLAG,
    COUNT(*) AS RECORD_COUNT
FROM YELLOW_TAXI_RAW
GROUP BY STORE_AND_FWD_FLAG
ORDER BY STORE_AND_FWD_FLAG;

-- 6. Check passenger count

SELECT
    PASSENGER_COUNT,
    COUNT(*) AS RECORD_COUNT
FROM YELLOW_TAXI_RAW
GROUP BY PASSENGER_COUNT
ORDER BY PASSENGER_COUNT;

-- Check trips where passenger count is 0.
SELECT
    COUNT(*) AS ZERO_PASSENGER_RECORDS,
    COUNT_IF(TRIP_DISTANCE = 0) AS ZERO_DISTANCE_RECORDS,
    COUNT_IF(TRIP_DISTANCE > 0) AS POSITIVE_DISTANCE_RECORDS,
    COUNT_IF(TOTAL_AMOUNT = 0) AS ZERO_TOTAL_RECORDS,
    COUNT_IF(TOTAL_AMOUNT > 0) AS POSITIVE_TOTAL_RECORDS,
    COUNT_IF(TOTAL_AMOUNT < 0) AS NEGATIVE_TOTAL_RECORDS
FROM YELLOW_TAXI_RAW
WHERE PASSENGER_COUNT = 0;

-- Check unusually high passenger counts.
SELECT
    PASSENGER_COUNT,
    COUNT(*) AS RECORD_COUNT
FROM YELLOW_TAXI_RAW
WHERE PASSENGER_COUNT >= 7
GROUP BY PASSENGER_COUNT
ORDER BY PASSENGER_COUNT;

-- 7. Check trip distance

SELECT
    COUNT_IF(TRIP_DISTANCE < 0) AS NEGATIVE_DISTANCE,
    COUNT_IF(TRIP_DISTANCE = 0) AS ZERO_DISTANCE,
    COUNT_IF(TRIP_DISTANCE > 0) AS POSITIVE_DISTANCE
FROM YELLOW_TAXI_RAW;

-- Check very large distance values.
SELECT
    COUNT_IF(TRIP_DISTANCE > 100) AS OVER_100_MILES,
    COUNT_IF(TRIP_DISTANCE > 200) AS OVER_200_MILES,
    COUNT_IF(TRIP_DISTANCE > 500) AS OVER_500_MILES,
    COUNT_IF(TRIP_DISTANCE > 1000) AS OVER_1000_MILES,
    MAX(TRIP_DISTANCE) AS MAX_DISTANCE
FROM YELLOW_TAXI_RAW;

-- Look at the records with extremely large distances.
SELECT
    VENDORID,
    TPEP_PICKUP_DATETIME,
    TPEP_DROPOFF_DATETIME,
    TRIP_DISTANCE,
    PASSENGER_COUNT,
    PAYMENT_TYPE,
    FARE_AMOUNT,
    TOTAL_AMOUNT
FROM YELLOW_TAXI_RAW
WHERE TRIP_DISTANCE > 1000
ORDER BY TRIP_DISTANCE DESC
LIMIT 20;

-- 8. Check negative financial values

SELECT
    COUNT_IF(FARE_AMOUNT < 0) AS NEGATIVE_FARE,
    COUNT_IF(EXTRA < 0) AS NEGATIVE_EXTRA,
    COUNT_IF(MTA_TAX < 0) AS NEGATIVE_MTA_TAX,
    COUNT_IF(TIP_AMOUNT < 0) AS NEGATIVE_TIP,
    COUNT_IF(TOLLS_AMOUNT < 0) AS NEGATIVE_TOLLS,
    COUNT_IF(IMPROVEMENT_SURCHARGE < 0) AS NEGATIVE_IMPROVEMENT_SURCHARGE,
    COUNT_IF(CONGESTION_SURCHARGE < 0) AS NEGATIVE_CONGESTION_SURCHARGE,
    COUNT_IF(AIRPORT_FEE < 0) AS NEGATIVE_AIRPORT_FEE,
    COUNT_IF(TOTAL_AMOUNT < 0) AS NEGATIVE_TOTAL
FROM YELLOW_TAXI_RAW;

-- 9. Check negative fares against total amount

SELECT
    COUNT(*) AS NEGATIVE_FARE_RECORDS,
    COUNT_IF(TOTAL_AMOUNT < 0) AS NEGATIVE_TOTAL,
    COUNT_IF(TOTAL_AMOUNT >= 0) AS NON_NEGATIVE_TOTAL
FROM YELLOW_TAXI_RAW
WHERE FARE_AMOUNT < 0;

-- Look at negative fare records where total amount is not negative.
SELECT
    VENDORID,
    TPEP_PICKUP_DATETIME,
    TPEP_DROPOFF_DATETIME,
    PASSENGER_COUNT,
    TRIP_DISTANCE,
    PULOCATIONID,
    DOLOCATIONID,
    PAYMENT_TYPE,
    FARE_AMOUNT,
    TIP_AMOUNT,
    TOLLS_AMOUNT,
    TOTAL_AMOUNT
FROM YELLOW_TAXI_RAW
WHERE FARE_AMOUNT < 0
  AND TOTAL_AMOUNT >= 0
ORDER BY FARE_AMOUNT;

-- 10. Check pickup and dropoff times

SELECT
    MIN(TO_TIMESTAMP_NTZ(TPEP_PICKUP_DATETIME / 1000000)) AS MIN_PICKUP,
    MAX(TO_TIMESTAMP_NTZ(TPEP_PICKUP_DATETIME / 1000000)) AS MAX_PICKUP,
    MIN(TO_TIMESTAMP_NTZ(TPEP_DROPOFF_DATETIME / 1000000)) AS MIN_DROPOFF,
    MAX(TO_TIMESTAMP_NTZ(TPEP_DROPOFF_DATETIME / 1000000)) AS MAX_DROPOFF
FROM YELLOW_TAXI_RAW;

-- Check whether any trip ends before it starts.
SELECT
    COUNT_IF(TPEP_DROPOFF_DATETIME < TPEP_PICKUP_DATETIME)
        AS DROPOFF_BEFORE_PICKUP,
    COUNT_IF(TPEP_DROPOFF_DATETIME = TPEP_PICKUP_DATETIME)
        AS SAME_TIMESTAMP,
    COUNT_IF(TPEP_DROPOFF_DATETIME > TPEP_PICKUP_DATETIME)
        AS POSITIVE_DURATION
FROM YELLOW_TAXI_RAW;

-- Look at trips where dropoff is before pickup.
SELECT
    VENDORID,
    TPEP_PICKUP_DATETIME,
    TPEP_DROPOFF_DATETIME,
    TRIP_DISTANCE,
    PASSENGER_COUNT,
    PULOCATIONID,
    DOLOCATIONID,
    PAYMENT_TYPE,
    FARE_AMOUNT,
    TOTAL_AMOUNT
FROM YELLOW_TAXI_RAW
WHERE TPEP_DROPOFF_DATETIME < TPEP_PICKUP_DATETIME;

-- Check trips with the same pickup and dropoff timestamp.
SELECT
    COUNT(*) AS SAME_TIMESTAMP_RECORDS,
    COUNT_IF(TRIP_DISTANCE = 0) AS ZERO_DISTANCE,
    COUNT_IF(TRIP_DISTANCE > 0) AS POSITIVE_DISTANCE,
    COUNT_IF(TOTAL_AMOUNT = 0) AS ZERO_TOTAL,
    COUNT_IF(TOTAL_AMOUNT > 0) AS POSITIVE_TOTAL,
    COUNT_IF(TOTAL_AMOUNT < 0) AS NEGATIVE_TOTAL
FROM YELLOW_TAXI_RAW
WHERE TPEP_DROPOFF_DATETIME = TPEP_PICKUP_DATETIME;

-- 11. Check location IDs

SELECT
    MIN(PULOCATIONID) AS MIN_PICKUP_LOCATION,
    MAX(PULOCATIONID) AS MAX_PICKUP_LOCATION,
    MIN(DOLOCATIONID) AS MIN_DROPOFF_LOCATION,
    MAX(DOLOCATIONID) AS MAX_DROPOFF_LOCATION
FROM YELLOW_TAXI_RAW;

-- Check pickup and dropoff IDs against the taxi zone lookup table.
SELECT
    COUNT_IF(p.LOCATIONID IS NULL) AS INVALID_PICKUP_IDS,
    COUNT_IF(d.LOCATIONID IS NULL) AS INVALID_DROPOFF_IDS
FROM YELLOW_TAXI_RAW t
LEFT JOIN NYC_TAXI_DQ.LOOKUP.TAXI_ZONE_LOOKUP p
    ON t.PULOCATIONID = p.LOCATIONID
LEFT JOIN NYC_TAXI_DQ.LOOKUP.TAXI_ZONE_LOOKUP d
    ON t.DOLOCATIONID = d.LOCATIONID;


-- 12. Check missing values

SELECT
    COUNT_IF(PASSENGER_COUNT IS NULL) AS NULL_PASSENGER_COUNT,
    COUNT_IF(RATECODEID IS NULL) AS NULL_RATECODEID,
    COUNT_IF(STORE_AND_FWD_FLAG IS NULL) AS NULL_STORE_AND_FWD,
    COUNT_IF(CONGESTION_SURCHARGE IS NULL) AS NULL_CONGESTION,
    COUNT_IF(AIRPORT_FEE IS NULL) AS NULL_AIRPORT_FEE,
    COUNT_IF(CBD_CONGESTION_FEE IS NULL) AS NULL_CBD_CONGESTION_FEE
FROM YELLOW_TAXI_RAW;

-- Check whether the missing values are related to payment type.
SELECT
    PAYMENT_TYPE,
    COUNT(*) AS TOTAL_RECORDS,
    COUNT_IF(PASSENGER_COUNT IS NULL) AS NULL_PASSENGER_COUNT,
    COUNT_IF(RATECODEID IS NULL) AS NULL_RATECODEID,
    COUNT_IF(STORE_AND_FWD_FLAG IS NULL) AS NULL_STORE_AND_FWD,
    COUNT_IF(CONGESTION_SURCHARGE IS NULL) AS NULL_CONGESTION,
    COUNT_IF(AIRPORT_FEE IS NULL) AS NULL_AIRPORT_FEE,
    COUNT_IF(CBD_CONGESTION_FEE IS NULL) AS NULL_CBD_CONGESTION_FEE
FROM YELLOW_TAXI_RAW
GROUP BY PAYMENT_TYPE
ORDER BY PAYMENT_TYPE;

-- 13. Check text values

-- Check for leading or trailing spaces.
SELECT
    COUNT_IF(
        STORE_AND_FWD_FLAG != TRIM(STORE_AND_FWD_FLAG)
    ) AS LEADING_TRAILING_SPACES
FROM YELLOW_TAXI_RAW;

-- Check for lowercase values.
SELECT
    COUNT_IF(
        STORE_AND_FWD_FLAG IS NOT NULL
        AND STORE_AND_FWD_FLAG = LOWER(STORE_AND_FWD_FLAG)
    ) AS LOWERCASE_VALUES
FROM YELLOW_TAXI_RAW;

-- Check for empty strings.
SELECT
    COUNT_IF(STORE_AND_FWD_FLAG = '') AS EMPTY_STRINGS
FROM YELLOW_TAXI_RAW;

-- Check for blank or whitespace-only values.
SELECT
    COUNT_IF(
        STORE_AND_FWD_FLAG IS NOT NULL
        AND TRIM(STORE_AND_FWD_FLAG) = ''
    ) AS BLANK_OR_WHITESPACE_VALUES
FROM YELLOW_TAXI_RAW;

-- Check which text values are actually present.
SELECT
    STORE_AND_FWD_FLAG,
    COUNT(*) AS RECORD_COUNT
FROM YELLOW_TAXI_RAW
GROUP BY STORE_AND_FWD_FLAG
ORDER BY STORE_AND_FWD_FLAG;

-- 14. Check TOTAL_AMOUNT against the other financial fields
-- EXTRA is not included here because the earlier check showed
-- that including it created a difference equal to EXTRA.

SELECT
    COUNT(*) AS TOTAL_RECORDS,
    COUNT_IF(
        ABS(
            TOTAL_AMOUNT -
            (
                FARE_AMOUNT
                + MTA_TAX
                + TIP_AMOUNT
                + TOLLS_AMOUNT
                + IMPROVEMENT_SURCHARGE
                + CONGESTION_SURCHARGE
                + AIRPORT_FEE
                + CBD_CONGESTION_FEE
            )
        ) < 0.01
    ) AS MATCHING_TOTALS,
    COUNT_IF(
        ABS(
            TOTAL_AMOUNT -
            (
                FARE_AMOUNT
                + MTA_TAX
                + TIP_AMOUNT
                + TOLLS_AMOUNT
                + IMPROVEMENT_SURCHARGE
                + CONGESTION_SURCHARGE
                + AIRPORT_FEE
                + CBD_CONGESTION_FEE
            )
        ) >= 0.01
    ) AS DIFFERENT_TOTALS
FROM YELLOW_TAXI_RAW
WHERE PAYMENT_TYPE <> 0;

-- 15. Check important fields for NULL values

SELECT
    COUNT_IF(VENDORID IS NULL) AS NULL_VENDORID,
    COUNT_IF(TPEP_PICKUP_DATETIME IS NULL) AS NULL_PICKUP,
    COUNT_IF(TPEP_DROPOFF_DATETIME IS NULL) AS NULL_DROPOFF,
    COUNT_IF(TRIP_DISTANCE IS NULL) AS NULL_DISTANCE,
    COUNT_IF(PULOCATIONID IS NULL) AS NULL_PICKUP_LOCATION,
    COUNT_IF(DOLOCATIONID IS NULL) AS NULL_DROPOFF_LOCATION,
    COUNT_IF(PAYMENT_TYPE IS NULL) AS NULL_PAYMENT_TYPE,
    COUNT_IF(FARE_AMOUNT IS NULL) AS NULL_FARE,
    COUNT_IF(TOTAL_AMOUNT IS NULL) AS NULL_TOTAL
FROM YELLOW_TAXI_RAW;

-- Check that ID and code columns contain whole numbers.
SELECT
    COUNT_IF(VENDORID != FLOOR(VENDORID)) AS FRACTIONAL_VENDORID,
    COUNT_IF(RATECODEID != FLOOR(RATECODEID)) AS FRACTIONAL_RATECODEID,
    COUNT_IF(PULOCATIONID != FLOOR(PULOCATIONID)) AS FRACTIONAL_PICKUP_LOCATION,
    COUNT_IF(DOLOCATIONID != FLOOR(DOLOCATIONID)) AS FRACTIONAL_DROPOFF_LOCATION,
    COUNT_IF(PAYMENT_TYPE != FLOOR(PAYMENT_TYPE)) AS FRACTIONAL_PAYMENT_TYPE
FROM YELLOW_TAXI_RAW;