-- NYC Taxi Data Cleaning Project
-- January 2026 Yellow Taxi Trip Records
-- Step 1: Data Profiling

-- 1. Check the total number of records
SELECT COUNT(*) AS TOTAL_ROWS
FROM NYC_TAXI_DQ.RAW.YELLOW_TAXI_RAW;

-- 2. Check the structure and data types of the raw table
SELECT
    COLUMN_NAME,
    DATA_TYPE,
    NUMERIC_PRECISION,
    NUMERIC_SCALE
FROM NYC_TAXI_DQ.INFORMATION_SCHEMA.COLUMNS
WHERE TABLE_SCHEMA = 'RAW'
  AND TABLE_NAME = 'YELLOW_TAXI_RAW'
ORDER BY ORDINAL_POSITION;

-- 3. Check missing values across all columns
SELECT
    COUNT_IF(VENDORID IS NULL) AS NULL_VENDORID,
    COUNT_IF(TPEP_PICKUP_DATETIME IS NULL) AS NULL_PICKUP_DATETIME,
    COUNT_IF(TPEP_DROPOFF_DATETIME IS NULL) AS NULL_DROPOFF_DATETIME,
    COUNT_IF(PASSENGER_COUNT IS NULL) AS NULL_PASSENGER_COUNT,
    COUNT_IF(TRIP_DISTANCE IS NULL) AS NULL_TRIP_DISTANCE,
    COUNT_IF(RATECODEID IS NULL) AS NULL_RATECODEID,
    COUNT_IF(STORE_AND_FWD_FLAG IS NULL) AS NULL_STORE_AND_FWD_FLAG,
    COUNT_IF(PULOCATIONID IS NULL) AS NULL_PICKUP_LOCATION,
    COUNT_IF(DOLOCATIONID IS NULL) AS NULL_DROPOFF_LOCATION,
    COUNT_IF(PAYMENT_TYPE IS NULL) AS NULL_PAYMENT_TYPE,
    COUNT_IF(FARE_AMOUNT IS NULL) AS NULL_FARE_AMOUNT,
    COUNT_IF(EXTRA IS NULL) AS NULL_EXTRA,
    COUNT_IF(MTA_TAX IS NULL) AS NULL_MTA_TAX,
    COUNT_IF(TIP_AMOUNT IS NULL) AS NULL_TIP_AMOUNT,
    COUNT_IF(TOLLS_AMOUNT IS NULL) AS NULL_TOLLS_AMOUNT,
    COUNT_IF(IMPROVEMENT_SURCHARGE IS NULL) AS NULL_IMPROVEMENT_SURCHARGE,
    COUNT_IF(TOTAL_AMOUNT IS NULL) AS NULL_TOTAL_AMOUNT,
    COUNT_IF(CONGESTION_SURCHARGE IS NULL) AS NULL_CONGESTION_SURCHARGE,
    COUNT_IF(AIRPORT_FEE IS NULL) AS NULL_AIRPORT_FEE,
    COUNT_IF(CBD_CONGESTION_FEE IS NULL) AS NULL_CBD_CONGESTION_FEE
FROM NYC_TAXI_DQ.RAW.YELLOW_TAXI_RAW;

-- 4. Check passenger count distribution
SELECT
    PASSENGER_COUNT,
    COUNT(*) AS RECORD_COUNT
FROM NYC_TAXI_DQ.RAW.YELLOW_TAXI_RAW
GROUP BY PASSENGER_COUNT
ORDER BY PASSENGER_COUNT;

-- 5. Check trip distance range and unusual values
SELECT
    MIN(TRIP_DISTANCE) AS MIN_DISTANCE,
    MAX(TRIP_DISTANCE) AS MAX_DISTANCE,
    COUNT_IF(TRIP_DISTANCE = 0) AS ZERO_DISTANCE,
    COUNT_IF(TRIP_DISTANCE < 0) AS NEGATIVE_DISTANCE
FROM NYC_TAXI_DQ.RAW.YELLOW_TAXI_RAW;


-- 6. Check raw timestamp range
SELECT
    MIN(TPEP_PICKUP_DATETIME) AS MIN_PICKUP_RAW,
    MAX(TPEP_PICKUP_DATETIME) AS MAX_PICKUP_RAW,
    MIN(TPEP_DROPOFF_DATETIME) AS MIN_DROPOFF_RAW,
    MAX(TPEP_DROPOFF_DATETIME) AS MAX_DROPOFF_RAW
FROM NYC_TAXI_DQ.RAW.YELLOW_TAXI_RAW;

-- 7. Convert the raw epoch values temporarily to readable timestamps
--    This is only for understanding the data. The raw table is not changed.
SELECT
    TO_TIMESTAMP_NTZ(TPEP_PICKUP_DATETIME / 1000000) AS PICKUP_DATETIME,
    TO_TIMESTAMP_NTZ(TPEP_DROPOFF_DATETIME / 1000000) AS DROPOFF_DATETIME
FROM NYC_TAXI_DQ.RAW.YELLOW_TAXI_RAW
LIMIT 10;